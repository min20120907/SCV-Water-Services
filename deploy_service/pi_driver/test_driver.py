#!/usr/bin/env python3
"""Runnable self-check for the SCV Water real-sensor driver (no hardware needed).

Covers the non-trivial logic that would silently break:
  1. BME280 compensation math vs the solved Bosch double-precision reference
     vector (T 25.0 C, P 1013.2 hPa, H 47.7 %RH).
  2. Full BME280 read path (fake I2C bus -> reg parse -> compensate -> dict).
  3. selftest contract: never raises; unknown type and out-of-range come back
     as structured results, not exceptions.

Run:  python3 test_driver.py
"""
import importlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
drv = importlib.import_module("driver")

# Solved reference vector: raw register bytes that the Bosch double-precision
# formulas map to (25.03 C, 1013.20 hPa, 34.87 %RH). Generated by inverting
# driver._bme280_read_regs and verified round-trip + compensation. The driver
# intentionally uses the int-truncated tfine (Bosch single-precision port),
# which shifts humidity by <0.001 %RH vs the pure double-precision reference.
CAL_HEX = "6c6bdc05e14582f2000000000000000000000000000000000031"
HUM_HEX = "1f0800010e0800"
DATA_HEX = "0a5dc00a4a600d6000000000"
TGT_T, TGT_P, TGT_H = 25.032322, 1013.202297, 34.866957


class FakeI2CBus:
    def __init__(self, cal, hum, data):
        self._map = {0x88: cal, 0xE1: hum, 0xF4: data}
        self.closed = False

    def read_i2c_block_data(self, addr, reg, count):
        return self._map[reg][:count]

    def read_byte_data(self, addr, reg):
        if reg == 0xD0:  # chip id
            return 0x58
        raise KeyError(reg)

    def write_byte_data(self, addr, reg, val):
        return None

    def close(self):
        self.closed = True


def test_compensation_vector():
    cal, hum, data = bytes.fromhex(CAL_HEX), bytes.fromhex(HUM_HEX), bytes.fromhex(DATA_HEX)
    d, adc_t, adc_p, adc_h = drv._bme280_read_regs(FakeI2CBus(cal, hum, data), 0x76)
    out = drv._bme280_compensate(d, adc_t, adc_p, adc_h)
    assert abs(out["temp"] - TGT_T) < 0.05, out
    assert abs(out["pressure"] - TGT_P) < 0.05, out
    assert abs(out["humidity"] - TGT_H) < 0.05, out


def test_full_read_path():
    real = drv.smbus2
    drv.smbus2 = type("M", (), {"SMBus": staticmethod(lambda n: FakeI2CBus(
        bytes.fromhex(CAL_HEX), bytes.fromhex(HUM_HEX), bytes.fromhex(DATA_HEX)))})
    try:
        out = drv._bme280_read_cfg({"bus": 1, "address": 0x76})
    finally:
        drv.smbus2 = real
    assert abs(out["temp"] - TGT_T) < 0.05, out
    assert abs(out["pressure"] - TGT_P) < 0.05, out
    assert abs(out["humidity"] - TGT_H) < 0.05, out


def test_selftest_contract():
    r = drv.run_selftest({"device_id": "X", "type": "nope"})
    assert r["ok"] is False and r["error"] == drv.BAD_CODE, r

    # i2c_scan must not crash when a bus node is missing: absent bus -> [].
    real = drv.smbus2
    drv.smbus2 = type("M", (), {"SMBus": lambda n: (_ for _ in ()).throw(
        OSError("No such file or directory: '/dev/i2c-%d'" % n))})
    try:
        out = drv.i2c_scan((0, 1))
    finally:
        drv.smbus2 = real
    assert out == {"0": [], "1": []}, out

    code = "def read(config):\n    return {'lux': 1234.0}\n"
    r = drv.run_selftest({
        "device_id": "X", "type": "custom", "code": code,
        "fields": [{"key": "lux", "label": "L", "unit": "lx", "min": 0, "max": 1000}],
    })
    assert r["ok"] is False and r["error"] == drv.OUT_OF_RANGE, r

    r = drv.run_selftest({
        "device_id": "X", "type": "custom",
        "code": "def read(config):\n    return {'lux': 42.0}\n",
        "fields": [{"key": "lux", "label": "L", "unit": "lx", "min": 0, "max": 65535}],
    })
    assert r["ok"] is True and r["error"] == drv.OK, r


if __name__ == "__main__":
    for name, fn in sorted((k, v) for k, v in globals().items() if k.startswith("test_")):
        fn()
        print("PASS", name)
    print("ALL PASS")
